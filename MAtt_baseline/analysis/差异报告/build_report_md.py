def build():
    st = json.load(open(R/'individual_diff'/'subject_table.json', encoding='utf-8'))
    erd = json.load(open(R/'erd_decomposition'/'erd_decomposition.json', encoding='utf-8'))
    # 2026-10-30: 新口径(62.5 Hz)逐级探针优先,缺省回退旧 250 Hz
    _pa = R/'pipeline_attribution_62.5hz'/'pipeline_attribution.json'
    if not _pa.exists():
        _pa = R/'pipeline_attribution'/'pipeline_attribution.json'
    pa = json.load(open(_pa, encoding='utf-8'))
    vs = json.load(open(R/'val_selection_audit'/'val_selection_audit.json', encoding='utf-8'))
    runs = list(pa['runs'].keys())
    D = {'acc': {}, 'std': {}, 'erd': {}, 'row': {}, 'runs': runs}
    # 2026-10-30: 逐人精度改用新口径(62.5 Hz + 可分离)的 best_acc 复评;缺省回退旧 deep70
    _ev = R/'sep62_eval'/'sep62_eval.json'
    ev = json.loads(_ev.read_text(encoding='utf-8'))['per_subject'] if _ev.exists() else None
    for r in st:
        s = r['subject']
        if ev and s in ev:
            D['acc'][s] = ev[s]['mean'] * 100
            D['std'][s] = (ev[s]['max'] - ev[s]['min']) / 2 * 100
        else:
            D['acc'][s] = r['deep70_acc'] * 100
            D['std'][s] = r['deep70_std'] * 100
        D['row'][s] = r
        D['erd'][s] = erd['per_subject'][s]
    lv = ['01_入口_22通道协方差', 'conv1_协方差', 'conv2_协方差',
          'E2R出口_log均值', 'SPDNorm后_log均值', '后端切空间出口']
    D['lv'] = lv
    D['lo'] = [sum(pa['runs'][s]['trace'][l]['low4_full'] for s in runs)/len(runs)*100 for l in lv]
    D['hi'] = [sum(pa['runs'][s]['trace'][l]['high5_full'] for s in runs)/len(runs)*100 for l in lv]
    # 共享读出（与模型同条件：不用被试身份，训练=非测试折，测试=同一 778 试次）
    D['slo'] = [sum(pa['runs'][s]['trace'][l]['shared_low4'] for s in runs)/len(runs)*100 for l in lv]
    D['shi'] = [sum(pa['runs'][s]['trace'][l]['shared_high5'] for s in runs)/len(runs)*100 for l in lv]
    D['sov'] = [sum(pa['runs'][s]['trace'][l]['shared_test'] for s in runs)/len(runs)*100 for l in lv]
    D['model_lo'] = sum(D['acc'][s] for s in LOW4)/len(LOW4)
    D['model_hi'] = sum(D['acc'][s] for s in HIGH5)/len(HIGH5)
    D['model_ov'] = sum(D['acc'].values())/len(D['acc'])
    D['basis'] = {}
    for k in ['all22', 'conv1_22dir', 'conv1_top8_to_lda', 'subject_pca8']:
        D['basis'][k] = tuple(sum(pa['runs'][s]['basis_comparison'][k]['low4_high5'][i] for s in runs)/len(runs)*100 for i in (0, 1))
    D['r8'] = sum(pa['runs'][s]['basis_comparison']['random8_mean'] for s in runs)/len(runs)*100
    D['r8_lo'] = sum(pa['runs'][s]['basis_comparison']['random8_low4_mean'] for s in runs)/len(runs)*100
    D['r8_hi'] = sum(pa['runs'][s]['basis_comparison']['random8_high5_mean'] for s in runs)/len(runs)*100
    D['r8_sd'] = sum(pa['runs'][s]['basis_comparison']['random8_low4_std'] for s in runs)/len(runs)*100
    # conv1_top8 与随机基的差（同口径：逐人 5 折）
    D['top8_minus_r8_lo'] = D['basis']['conv1_top8_to_lda'][0] - D['r8_lo']
    D['top8_minus_r8_hi'] = D['basis']['conv1_top8_to_lda'][1] - D['r8_hi']
    D['vs'] = vs
    return D


